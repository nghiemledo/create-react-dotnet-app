// Generates TypeScript types for the backend API from its OpenAPI (Swagger) document.
// Usage: npm run codegen [-- --input <url-or-file>] [--output <file>] [--check]
import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';

const CLIENT_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DEFAULT_INPUT = 'http://localhost:5058/swagger/v1/swagger.json';
const DEFAULT_OUTPUT = path.join(CLIENT_DIR, 'src', 'types', 'api.generated.ts');
const FETCH_TIMEOUT_MS = 15_000;
const START_API_HINT =
  'Start the API in the Development environment first (Swagger is only served there):\n' +
  '  cd server && dotnet run --project ReactDotnetBoilerplate.Api --launch-profile https\n' +
  'or pass a saved document: npm run codegen -- --input path/to/swagger.json';

/** First line of every generated file; an existing output file without it is never overwritten. */
export const GENERATED_MARKER = '// <auto-generated> by client/scripts/codegen.mjs. Do not edit this file by hand.';
const HEADER = [
  GENERATED_MARKER,
  '// Source: the backend OpenAPI document (Swagger "v1"). Change the API, then run the codegen script again.',
  '',
  '',
].join('\n');

class CodegenError extends Error {}

function parseCliArgs(argv) {
  try {
    const { values } = parseArgs({
      args: argv,
      options: {
        input: { type: 'string', default: DEFAULT_INPUT },
        output: { type: 'string', default: DEFAULT_OUTPUT },
        check: { type: 'boolean', default: false },
      },
      strict: true,
      allowPositionals: false,
    });
    return values;
  } catch (error) {
    throw new CodegenError(`${error.message}\nUsage: npm run codegen [-- --input <url-or-file>] [--output <file>] [--check]`);
  }
}

async function fetchDocument(url) {
  let response;
  try {
    response = await fetch(url, { signal: AbortSignal.timeout(FETCH_TIMEOUT_MS), headers: { accept: 'application/json' } });
  } catch (error) {
    const cause = error.cause?.code ?? error.cause?.message ?? error.name;
    if (/CERT|SELF_SIGNED|UNABLE_TO_VERIFY/i.test(String(cause))) {
      throw new CodegenError(
        `Could not verify the HTTPS certificate of ${url} (${cause}). Node.js does not trust the ASP.NET Core development certificate; use the HTTP URL instead: ${DEFAULT_INPUT}`,
      );
    }
    const reason = error.name === 'TimeoutError' ? `no response within ${FETCH_TIMEOUT_MS / 1000}s` : cause;
    throw new CodegenError(`Could not reach the backend at ${url} (${reason}).\n${START_API_HINT}`);
  }

  if (response.status === 404) {
    throw new CodegenError(
      `No OpenAPI document at ${url} (HTTP 404). Check the URL; the API only serves /swagger/v1/swagger.json when ASPNETCORE_ENVIRONMENT=Development.`,
    );
  }
  if (!response.ok) {
    throw new CodegenError(`The backend answered ${url} with HTTP ${response.status} ${response.statusText}. Check the API console output.`);
  }
  return { text: await response.text(), label: url };
}

async function readDocumentFile(file) {
  const resolved = path.resolve(file);
  try {
    return { text: await readFile(resolved, 'utf8'), label: resolved };
  } catch (error) {
    if (error.code === 'ENOENT') {
      throw new CodegenError(`OpenAPI file not found: ${resolved}`);
    }
    throw new CodegenError(`Could not read ${resolved}: ${error.message}`);
  }
}

/** Rejects anything that would produce empty or meaningless types. */
export function validateDocument(text, label) {
  let document;
  try {
    document = JSON.parse(text.charCodeAt(0) === 0xfeff ? text.slice(1) : text);
  } catch {
    const preview = text.trim().slice(0, 60).replace(/\s+/g, ' ');
    throw new CodegenError(`${label} is not valid JSON (starts with: "${preview}"). Expected the Swagger JSON document, not the Swagger UI page.`);
  }
  if (typeof document !== 'object' || document === null || Array.isArray(document)) {
    throw new CodegenError(`${label} is not an OpenAPI document (expected a JSON object).`);
  }
  if (typeof document.openapi !== 'string' || !/^3\.[01]\./.test(document.openapi)) {
    const found = document.openapi ?? (document.swagger ? `swagger ${document.swagger}` : 'no "openapi" field');
    throw new CodegenError(`${label} is not an OpenAPI 3.0/3.1 document (found ${found}).`);
  }
  const pathCount = typeof document.paths === 'object' && document.paths !== null ? Object.keys(document.paths).length : 0;
  if (pathCount === 0) {
    throw new CodegenError(`${label} defines no API paths; refusing to generate empty types.`);
  }
  return document;
}

const byKey = ([a], [b]) => (a < b ? -1 : a > b ? 1 : 0);
const sortKeys = (record) => Object.fromEntries(Object.entries(record).sort(byKey));

/**
 * Swashbuckle does not guarantee the order of paths (the minimal API "/" route moves between runs of
 * the same API), so paths and component maps are sorted to make the output depend only on the content.
 */
export function sortForStableOutput(document) {
  const sorted = { ...document, paths: sortKeys(document.paths) };
  if (typeof document.components === 'object' && document.components !== null) {
    sorted.components = Object.fromEntries(
      Object.entries(document.components).map(([kind, map]) => [kind, typeof map === 'object' && map !== null ? sortKeys(map) : map]),
    );
  }
  return sorted;
}

async function generate(document, label) {
  let openapiTS;
  let astToString;
  try {
    ({ default: openapiTS, astToString } = await import('openapi-typescript'));
  } catch {
    throw new CodegenError('openapi-typescript is not installed. Install the client dependencies first (pnpm install or npm install).');
  }

  let source;
  try {
    source = astToString(await openapiTS(sortForStableOutput(document), { silent: true }));
  } catch (error) {
    throw new CodegenError(`${label} is not a valid OpenAPI document: ${error.message}`);
  }
  if (!/^export interface paths \{/m.test(source) || !/^export interface components \{/m.test(source)) {
    throw new CodegenError('openapi-typescript produced unexpected output; the generated file was not written.');
  }
  return `${HEADER}${source.replace(/\r\n/g, '\n')}`;
}

async function readExisting(file) {
  try {
    return (await readFile(file, 'utf8')).replace(/\r\n/g, '\n');
  } catch (error) {
    if (error.code === 'ENOENT') {
      return undefined;
    }
    throw error;
  }
}

export async function run(argv) {
  const options = parseCliArgs(argv);
  const output = path.resolve(options.output);
  const isUrl = /^https?:\/\//i.test(options.input);

  const { text, label } = isUrl ? await fetchDocument(options.input) : await readDocumentFile(options.input);
  const content = await generate(validateDocument(text, label), label);
  const existing = await readExisting(output);
  const relativeOutput = path.relative(process.cwd(), output) || output;

  if (existing !== undefined && !existing.startsWith(GENERATED_MARKER)) {
    throw new CodegenError(`${relativeOutput} exists and was not created by codegen; refusing to overwrite it. Move it or pass --output.`);
  }
  if (options.check) {
    if (existing !== content) {
      throw new CodegenError(`${relativeOutput} is out of date with ${label}. Run npm run codegen.`);
    }
    console.log(`codegen: ${relativeOutput} is up to date.`);
    return;
  }
  if (existing === content) {
    console.log(`codegen: ${relativeOutput} is already up to date.`);
    return;
  }

  await mkdir(path.dirname(output), { recursive: true });
  const temporary = `${output}.${process.pid}.tmp`;
  try {
    await writeFile(temporary, content, 'utf8');
    await rename(temporary, output);
  } finally {
    await rm(temporary, { force: true });
  }
  console.log(`codegen: wrote ${relativeOutput} from ${label}.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  run(process.argv.slice(2)).catch((error) => {
    console.error(`codegen: ${error instanceof CodegenError ? error.message : error.stack ?? error}`);
    process.exitCode = 1;
  });
}
